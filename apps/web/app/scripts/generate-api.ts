import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

const DEFAULT_API_URL = 'http://localhost:3000';
const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'] as const;

/**
 * Normalizes known Swagger generation quirks in the live `/openapi.json`
 * without modifying `apps/api`:
 * 1. `@All('mcp')` emits the same `operationId` across every HTTP method on
 *    `/api/v1/mcp` — disambiguate repeats by appending `_${method}`.
 * 2. `SyncChangeDto.snapshot` uses raw `$ref`s for `TagSnapshotDto` and
 *    `CollectionSnapshotDto`, which NestJS Swagger omits from
 *    `components.schemas` when not registered via `@ApiExtraModels`.
 */
function normalizeOpenApiDocument(document: OpenAPI3): OpenAPI3 {
  const seen = new Set<string>();
  const paths = document.paths ?? {};

  for (const pathItem of Object.values(paths)) {
    if (!pathItem || typeof pathItem !== 'object' || '$ref' in pathItem) continue;
    const record = pathItem as Record<string, unknown>;
    for (const method of HTTP_METHODS) {
      const op = record[method];
      if (!op || typeof op !== 'object' || !('operationId' in op)) continue;
      const opObj = op as { operationId?: string };
      const id = opObj.operationId;
      if (!id) continue;
      if (seen.has(id)) {
        opObj.operationId = `${id}_${method}`;
      }
      seen.add(opObj.operationId ?? id);
    }
  }

  document.components ??= {};
  document.components.schemas ??= {};
  const schemas = document.components.schemas;

  schemas['TagSnapshotDto'] ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      name: { type: 'string' },
      createdAt: { type: 'string', format: 'date-time' },
      updatedAt: { type: 'string', format: 'date-time' },
    },
    required: ['id', 'name', 'createdAt', 'updatedAt'],
  };

  schemas['CollectionSnapshotDto'] ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      parentId: { type: 'string', format: 'uuid', nullable: true },
      title: { type: 'string' },
      icon: { type: 'string', nullable: true },
      color: { type: 'string', nullable: true },
      order: { type: 'number' },
      share: { $ref: '#/components/schemas/CollectionShareDto' },
      createdAt: { type: 'string', format: 'date-time' },
      updatedAt: { type: 'string', format: 'date-time' },
      deletedAt: { type: 'string', format: 'date-time', nullable: true },
    },
    required: [
      'id',
      'parentId',
      'title',
      'icon',
      'color',
      'order',
      'share',
      'createdAt',
      'updatedAt',
      'deletedAt',
    ],
  };

  return document;
}

async function formatWithPrettier(source: string, filepath: string): Promise<string> {
  try {
    const prettier = await import('prettier');
    const config = await prettier.resolveConfig(filepath);
    return await prettier.format(source, { ...config, filepath });
  } catch {
    return source;
  }
}

async function main(): Promise<void> {
  const rawBaseUrl = process.env['ARCDROP__API_URL']?.trim() || DEFAULT_API_URL;
  const specUrl = rawBaseUrl.endsWith('/openapi.json')
    ? rawBaseUrl
    : `${rawBaseUrl.replace(/\/+$/, '')}/openapi.json`;

  let response: Response;
  try {
    response = await fetch(specUrl);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(
      `Failed to fetch OpenAPI schema from ${specUrl}: ${message}\n` +
        'Start the ArcDrop API first (e.g. `docker compose up -d` or `bun --cwd=apps/api run dev`) ' +
        'or set ARCDROP__API_URL to a running instance.',
    );
    process.exit(1);
  }

  if (!response.ok) {
    console.error(
      `OpenAPI fetch from ${specUrl} returned HTTP ${response.status} ${response.statusText}.`,
    );
    process.exit(1);
  }

  const document = normalizeOpenApiDocument((await response.json()) as OpenAPI3);
  const ast = await openapiTS(document, {
    alphabetize: true,
    exportType: true,
  });

  const banner = [
    '// Auto-generated by `bun run generate:api` via openapi-typescript. Do not hand-edit.',
    '',
  ].join('\n');

  const rawOutput = `${banner}${astToString(ast)}`;

  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const outFile = path.resolve(scriptDir, '../src/api/types.ts');
  await mkdir(path.dirname(outFile), { recursive: true });

  const formatted = await formatWithPrettier(rawOutput, outFile);
  await writeFile(outFile, formatted, 'utf8');
  console.log(`Generated ${path.relative(process.cwd(), outFile)} from ${specUrl}`);
}

void main();
