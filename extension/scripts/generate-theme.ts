// Generates extension/shared/theme-palettes.gen.ts from the WEB APP's
// Material You palette registry (apps/web/app/src/theme/palettes/
// materialYou.ts). Keeps the extension's palette selector in perfect sync
// with the web app without hand-copying hex values — the same committed-
// artifact pattern as generate:api.
//
//   bun --cwd=extension run generate:theme
// Rerun whenever the web palettes change. Never run by CI.

import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));

// Cross-project TS import — bun resolves it the same way the smoke scripts do.
const { MATERIAL_YOU_PALETTES, MATERIAL_YOU_SEMANTIC } =
  await import('../../apps/web/app/src/theme/palettes/materialYou.ts');

const MODES = ['light', 'dark'] as const;
const SCHEME_FIELDS = [
  'primary',
  'onPrimary',
  'secondary',
  'onSecondary',
  'background',
  'surface',
  'onSurface',
  'onSurfaceVariant',
  'outlineVariant',
] as const;

type Palette = (typeof MATERIAL_YOU_PALETTES)[number];

const palettes = (MATERIAL_YOU_PALETTES as Palette[]).map((palette) => ({
  id: palette.id,
  label: palette.label,
  swatch: [...palette.swatch],
  schemes: Object.fromEntries(
    MODES.map((mode) => [
      mode,
      Object.fromEntries(
        SCHEME_FIELDS.map((field) => [
          field,
          (palette.schemes[mode] as Record<string, string>)[field],
        ]),
      ),
    ]),
  ),
}));

const banner =
  '// Auto-generated by `bun --cwd=extension run generate:theme` from\n' +
  '// apps/web/app/src/theme/palettes/materialYou.ts. Do not hand-edit —\n' +
  '// regenerate when the web palettes change.\n\n';

const body = [
  `export interface PaletteScheme {`,
  ...SCHEME_FIELDS.map((field) => `  ${field}: string;`),
  `}`,
  '',
  `export interface PaletteDefinition {`,
  `  id: string;`,
  `  label: string;`,
  `  /** Two representative colors (light-mode + dark-mode primary) for swatches. */`,
  `  swatch: [string, string];`,
  `  schemes: Record<'light' | 'dark', PaletteScheme>;`,
  `}`,
  '',
  `export const PALETTES: readonly PaletteDefinition[] = ${JSON.stringify(palettes, null, 2)} as const;`,
  '',
  `export const SEMANTIC_TONES: Record<'light' | 'dark', { error: string; warning: string; info: string; success: string }> =`,
  `${JSON.stringify(MATERIAL_YOU_SEMANTIC, null, 2)} as const;`,
  '',
  `export const DEFAULT_PALETTE_ID = PALETTES[0]?.id ?? 'violet';`,
  '',
].join('\n');

const outFile = path.resolve(scriptDir, '../shared/theme-palettes.gen.ts');
await writeFile(outFile, banner + body, 'utf8');
console.log(`Generated ${path.relative(process.cwd(), outFile)} (${palettes.length} palettes)`);
